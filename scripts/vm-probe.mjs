import { createCustomCommon, Hardfork, Mainnet } from '@ethereumjs/common';
import { createLegacyTx } from '@ethereumjs/tx';
import { createBlock } from '@ethereumjs/block';
import { createAccount, createAddressFromPrivateKey, hexToBytes, createAddressFromString } from '@ethereumjs/util';
import { createVM, runTx } from '@ethereumjs/vm';
import { ContractFactory, Interface, Wallet, getBytes, keccak256, toUtf8Bytes } from 'ethers';
import { contract, mock } from './compile-contract.cjs';
const common = createCustomCommon({ chainId: 31337, networkId: 31337 }, Mainnet, { hardfork: Hardfork.Paris });
const vm = await createVM({ common });
const issuer = Wallet.createRandom();
const executor = Wallet.createRandom();
for (const wallet of [issuer, executor]) await vm.stateManager.putAccount(createAddressFromString(wallet.address), createAccount({ nonce: 0n, balance: 10n ** 20n }));
const nonces = new Map([[issuer.address.toLowerCase(), 0n], [executor.address.toLowerCase(), 0n]]);
let blockNumber = 0n;
async function send(wallet, data, to) {
  const key = hexToBytes(wallet.privateKey);
  const tx = createLegacyTx({ nonce: nonces.get(wallet.address.toLowerCase()), gasLimit: 5_000_000n, gasPrice: 1_000_000_000n, value: 0n, ...(to ? { to: hexToBytes(to) } : {}), data: hexToBytes(data) }, { common }).sign(key);
  nonces.set(wallet.address.toLowerCase(), nonces.get(wallet.address.toLowerCase()) + 1n);
  const block = createBlock({ header: { number: blockNumber++, timestamp: 100n, gasLimit: 30_000_000n, baseFeePerGas: 0n } }, { common });
  const result = await runTx(vm, { tx, block });
  console.log('tx', wallet.address, result.receipt.status, result.createdAddress?.toString(), result.totalGasSpent, result.execResult.exceptionError?.error, result.execResult.exceptionError?.message, Buffer.from(result.execResult.returnValue).toString('hex'));
  return result;
}
const Mock = new ContractFactory(mock.abi, `0x${mock.evm.bytecode.object}`);
const Registry = new Interface(mock.abi);
const regInit = await Mock.getDeployTransaction();
const regRes = await send(issuer, regInit.data, null);
const regAddress = regRes.createdAddress.toString();
for (const wallet of [issuer, executor]) await send(issuer, Registry.encodeFunctionData('setBalance', [wallet.address, 1]), regAddress);
const Guard = new ContractFactory(contract.abi, `0x${contract.evm.bytecode.object}`);
const guardInit = await Guard.getDeployTransaction(regAddress);
const guardRes = await send(issuer, guardInit.data, null);
const guardAddress = guardRes.createdAddress.toString();
console.log('addresses',regAddress,guardAddress);
const guardInterface = new Interface(contract.abi);
const action=keccak256(toUtf8Bytes('MANDAVEX_DEMO_INCREMENT_V1'));
const payload=toUtf8Bytes('add one to my test counter');
const mandate={issuer:issuer.address,executor:executor.address,action,payloadHash:keccak256(payload),validAfter:0,expiry:9999999999,nonce:1,maxUses:1};
const signature=await issuer.signTypedData({name:'MANDAVEX',version:'1',chainId:31337,verifyingContract:guardAddress},{Mandate:[{name:'issuer',type:'address'},{name:'executor',type:'address'},{name:'action',type:'bytes32'},{name:'payloadHash',type:'bytes32'},{name:'validAfter',type:'uint64'},{name:'expiry',type:'uint64'},{name:'nonce',type:'uint256'},{name:'maxUses',type:'uint32'}]},mandate);
const exe=guardInterface.encodeFunctionData('execute',[mandate,payload,signature]);
const execRes=await send(executor,exe,guardAddress);
console.log('exec result',execRes.receipt.status,execRes.receipt.logs);
